def init_repo(proj_dir: Path, force: bool) -> bool:
    git_dir = proj_dir / ".git"
    if git_dir.exists():
        if not force:
            log_info(f"项目已存在 .git，跳过初始化: {proj_dir.relative_to(ROOT)}")
            return False
        log_warn("--force: 移除已有 .git 后重建")
        subprocess.run(["rm", "-rf", str(git_dir)], check=True)
    log_step(f"在项目目录初始化独立 git 仓库: {proj_dir.relative_to(ROOT)}")
    subprocess.run(["git", "-C", str(proj_dir), "init"], check=True,
                   capture_output=True, text=True)
    # 项目级 .gitignore
    gi = proj_dir / ".gitignore"
    gi.write_text(PROJECT_GITIGNORE_TPL, encoding="utf-8")
    log_info("已生成项目级 .gitignore（忽略 raw/、project/build 等体积产物）")

    # 剥离项目内"内嵌 git 仓库"（如 project/app/src/main/cpp/And64InlineHook 由前一轮
    # 工具克隆而来）。内嵌 .git 会被裸加为 gitlink(子模块引用)，导致该目录内容
    # 无法被本项目追踪与回滚。此处仅删除内嵌 .git 目录，使其成为普通文件。
    embedded = [
        p for p in proj_dir.rglob(".git")
        if p.is_dir() and p.parent != proj_dir  # 排除项目自身的 .git
    ]
    for p in embedded:
        log_warn(f"剥离内嵌 git 仓库: {p.relative_to(proj_dir).parent}")
        subprocess.run(["chmod", "-R", "u+w", str(p.parent)], check=False)
        subprocess.run(["rm", "-rf", str(p)], check=False)
    return True


def first_commit(proj_dir: Path) -> int:
    log_step("首次提交（初始基线快照）")
    subprocess.run(["git", "-C", str(proj_dir), "add", "-A"], check=True)
    r = subprocess.run(
        ["git", "-C", str(proj_dir), "commit",
         "-m", "init: project baseline (pre-stage-01)"],
        capture_output=True, text=True,
    )
    if r.returncode == 0:
        log_success("首次提交完成")
        # 统计
        lst = subprocess.run(["git", "-C", str(proj_dir), "ls-files"], capture_output=True, text=True)
        n = len(lst.stdout.splitlines())
        log_info(f"入库文件数: {n}")
        return 0
    # 无变更可提交（git commit 返回 1），非错误
    log_warn("首次提交: 无变更可提交（或仅空仓库）" if r.returncode == 1 else
             f"首次提交失败: {r.stderr.strip()}")
    return 0 if r.returncode == 1 else 1


def main() -> int:
    ensure_env()
    ap = argparse.ArgumentParser(description="给单个处理项目初始化嵌套独立 git 仓库")
    ap.add_argument("--name", required=True, help="项目名（CamelCase，折叠匹配 crackings/）")
    ap.add_argument("--type", default=None, help="引擎类型父目录（crackings/<type>/），多候选时消歧")
    ap.add_argument("--force", action="store_true", help="已有 .git 时移除重建")
    ap.add_argument("--no-commit", action="store_true", help="只 init + 生成 .gitignore，不做首次提交")
    args = ap.parse_args()

    proj_dir = locate_project(args.name, args.type)
    if not proj_dir:
        # 尝试精确目录
        cand = CRACKINGS_DIR / args.name
        if cand.is_dir():
            proj_dir = cand
        else:
            log_error(f"未定位到项目: crackings/**/{args.name}，请检查项目名或 --type")
            return 1

    created = init_repo(proj_dir, args.force)
    if not args.no_commit:
        rc = first_commit(proj_dir)
    else:
        rc = 0
        log_info("--no-commit: 已 init，跳过首次提交")
    log_success("[init-project-git] 完成")
    return rc


if __name__ == "__main__":
    sys.exit(main())