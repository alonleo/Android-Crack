#!/usr/bin/env python3
"""init-project-git.py — 给单个处理项目新建"嵌套独立 git 仓库"，用于子阶段提交与回滚。

背景（AGENTS.md 兼容）:
- 父仓库 .gitignore 整棵忽略 crackings/，故每个项目在自身目录内独立 `git init`，
  与父仓库互不干扰（嵌套仓库）。
- 结合「每完成一个子阶段 commit 一次 → 可回滚」的需求：
  本脚本负责初始化；阶段提交由 commit-project-stage.py 负责。

交付:
  1. crackings/<type>/<Name>/.git（若尚未存在）
  2. crackings/<type>/<Name>/.gitignore（项目级，忽略 raw/、project/build 等 GB 级产物，
     只追踪 status.yaml/findings.md/dir-index.yaml/stages 报告/脚本等过程产物）
  3. 首次提交（初始快照），此时已完成的阶段产物一并入库作为基线

用法:
  python3 init-project-git.py --name <Name> [--type <type>] [--force] [--no-commit]
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

# 让所有 print 立即 flush，避免与 log_*（stderr）交错时顺序错乱
import functools
print = functools.partial(print, flush=True)  # type: ignore[assignment]

ROOT = Path(__file__).resolve().parents[3]
LIB_DIR = Path(__file__).resolve().parents[0] / "lib"
sys.path.insert(0, str(LIB_DIR))
from common import (  # noqa: F403
    ensure_env,
    log_info,
    log_warn,
    log_success,
    log_error,
    log_step,
)

CRACKINGS_DIR = ROOT / "crackings"


def _fold(s: str) -> str:
    """匹配用折叠：小写 + 去除非字母数字（兼容 'Battle Tank' ↔ 'BattleTank'）。"""
    return "".join(ch for ch in s.lower() if ch.isalnum())


def locate_project(name: str, type_hint: str | None) -> Path | None:
    """在 crackings/ 下定位项目目录 crackings/<type>/<Name>/。

    优先精确 type；否则折叠子串匹配（type 父目录 + 遗留根目录工程）。
    匹配到多个时返回 None 并 warn（需 --type 消歧）。
    """
    kw = _fold(name)
    hits: list[Path] = []
    if not CRACKINGS_DIR.exists():
        return None
    for type_dir in sorted(p for p in CRACKINGS_DIR.iterdir() if p.is_dir()):
        if (type_dir / "status.yaml").exists() or (type_dir / "findings.md").exists():
            # 根目录遗留工程（直接是项目目录而非 type 父目录）
            if kw and kw in _fold(type_dir.name):
                hits.append(type_dir)
            continue
        if type_hint and _fold(type_hint) != _fold(type_dir.name):
            continue
        for proj in sorted(p for p in type_dir.iterdir() if p.is_dir()):
            if kw and kw in _fold(proj.name):
                hits.append(proj)
    if len(hits) == 1:
        return hits[0]
    if len(hits) > 1:
        found = ", ".join(str(h.relative_to(CRACKINGS_DIR)) for h in hits)
        log_warn(f"[init-project-git] 匹配到多个候选: {found}，请用 --type 消歧")
        return None
    # 遗留根目录工程兜底（已在上面环内收集，这里仅为覆盖 name 精确目录）
    cand = CRACKINGS_DIR / name
    if cand.is_dir() and any(cand.iterdir()):
        return cand
    return None


